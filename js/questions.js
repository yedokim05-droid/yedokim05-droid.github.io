(function () {
  "use strict";

  const thresholds = [2, 2, 2, 3, 3, 3, 3, 3, 2, 3, 3, 2, 3, 3, 3, 2, 3, 2];

  // 문항 text는 UI/채점 코드와 분리되어 있어 추후 문구 검수가 필요한 경우 이 배열만 수정하면 됩니다.
  const questionTexts = [
    "어려운 부분은 끝냈지만, 일의 세부적인 마무리를 하는 데 어려움을 느낀 적이 얼마나 자주 있습니까?",
    "체계적으로 정리해야 하는 일을 할 때, 순서에 맞게 일을 정리하는 데 어려움을 느낀 적이 얼마나 자주 있습니까?",
    "약속이나 해야 할 일을 기억하는 데 어려움을 느낀 적이 얼마나 자주 있습니까?",
    "많은 생각과 집중이 필요한 일을 해야 할 때, 시작을 피하거나 미루는 경우가 얼마나 자주 있습니까?",
    "오랫동안 앉아 있어야 할 때 손이나 발을 움직이거나 몸을 꼼지락거리는 경우가 얼마나 자주 있습니까?",
    "지나치게 활동적이거나, 마치 무언가에 의해 계속 움직여야 하는 것처럼 느끼는 경우가 얼마나 자주 있습니까?",
    "지루하거나 어려운 일을 할 때 부주의하게 실수하는 경우가 얼마나 자주 있습니까?",
    "지루하거나 반복적인 일을 할 때 집중을 유지하기 어려운 경우가 얼마나 자주 있습니까?",
    "상대방이 직접 이야기하고 있는데도 그 말에 집중하기 어려운 경우가 얼마나 자주 있습니까?",
    "집이나 직장에서 물건을 잘못 두거나 찾는 데 어려움을 겪는 경우가 얼마나 자주 있습니까?",
    "주변의 활동이나 소음 때문에 쉽게 주의가 흐트러지는 경우가 얼마나 자주 있습니까?",
    "회의나 다른 상황에서 계속 앉아 있어야 하는데 자리를 떠나는 경우가 얼마나 자주 있습니까?",
    "안절부절못하거나 초조한 느낌이 드는 경우가 얼마나 자주 있습니까?",
    "혼자 쉴 수 있는 시간이 있어도 긴장을 풀고 편안하게 쉬기 어려운 경우가 얼마나 자주 있습니까?",
    "다른 사람들과 함께 있을 때 말을 지나치게 많이 하는 경우가 얼마나 자주 있습니까?",
    "대화 중 상대방이 말을 끝내기도 전에 상대방이 하려는 말을 먼저 말하거나 문장을 완성하는 경우가 얼마나 자주 있습니까?",
    "자신의 차례를 기다려야 하는 상황에서 기다리는 것이 어려운 경우가 얼마나 자주 있습니까?",
    "다른 사람이 바쁘게 무언가를 하고 있을 때 끼어들거나 방해하는 경우가 얼마나 자주 있습니까?"
  ];

  const questions = questionTexts.map(function (text, index) {
    return {
      id: index + 1,
      part: index < 6 ? "A" : "B",
      text: text,
      threshold: thresholds[index]
    };
  });

  const answerOptions = [
    { value: 0, label: "전혀 없음" },
    { value: 1, label: "드물게" },
    { value: 2, label: "가끔" },
    { value: 3, label: "자주" },
    { value: 4, label: "매우 자주" }
  ];

  window.ADHDScreenerData = Object.freeze({
    questions: Object.freeze(questions),
    answerOptions: Object.freeze(answerOptions),
    thresholds: Object.freeze(thresholds)
  });
})();
